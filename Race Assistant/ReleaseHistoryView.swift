struct ReleaseHistoryView: View {
    @State private var expanded: Set<String> = []

    private var current: ReleaseNote {
        let version = ReleaseHistory.currentVersion
        let build = Int(ReleaseHistory.currentBuild) ?? 0
        return ReleaseHistory.known.first { $0.version == version && $0.build == build }
            ?? ReleaseNote(version: version, build: build,
                           changes: ["Примечания к этой сборке готовятся."])
    }

    private var previous: [ReleaseNote] {
        ReleaseHistory.known
            .filter { $0.build < current.build }
            .sorted { $0.build > $1.build }
    }

    var body: some View {
        List {
            Section("Текущая версия") {
                row(current)
            }
            if !previous.isEmpty {
                Section("Предыдущие версии") {
                    ForEach(previous, id: \.id) { entry in
                        row(entry)
                    }
                }
            }
        }
        .navigationTitle("Версии приложения")
    }

    private func row(_ entry: ReleaseNote) -> some View {
        DisclosureGroup(isExpanded: Binding(
            get: { expanded.contains(entry.id) },
            set: { isExpanded in
                if isExpanded { expanded.insert(entry.id) }
                else { expanded.remove(entry.id) }
            }
        )) {
            ForEach(entry.changes, id: \.self) { change in
                Text(change)
                    .font(.subheadline)
                    .padding(.vertical, 3)
            }
        } label: {
            Text(entry.title)
                .fontWeight(entry.id == current.id ? .semibold : .regular)
        }
    }
}
